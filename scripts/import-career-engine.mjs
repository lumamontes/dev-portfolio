#!/usr/bin/env node
// One-time (manually re-run) import from the separate, private career-engine
// project into this repo's own checked-in data file. Never a build-time
// dependency on that repo — see ticket 23 / docs/agents for why.
//
// Usage: node scripts/import-career-engine.mjs [path-to-career-engine]

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import matter from 'gray-matter';

const careerEngineRoot = process.argv[2] ?? join(process.env.HOME ?? '', 'www/career/career-engine');
const experiencesDir = join(careerEngineRoot, 'career/experiences');
const achievementsDir = join(careerEngineRoot, 'career/achievements');

const achievementFiles = readdirSync(achievementsDir).filter((f) => f.endsWith('.md') && !f.includes('example'));
const achievementsById = new Map(
  achievementFiles.map((file) => {
    const { data } = matter(readFileSync(join(achievementsDir, file), 'utf8'));
    return [data.id, { impact: data.impact?.trim(), importance: data.importance }];
  }),
);

const files = readdirSync(experiencesDir).filter((f) => f.endsWith('.md') && f !== 'README.md');

const experiences = files.map((file) => {
  const raw = readFileSync(join(experiencesDir, file), 'utf8');
  const { data, content } = matter(raw);
  const highlights = (data.achievements ?? [])
    .map((id) => achievementsById.get(id))
    .filter((achievement) => achievement?.impact)
    .map((achievement) => achievement.impact);
  return {
    company: data.company,
    location: data.location,
    period: data.period,
    roles: data.roles.map((role) => ({
      title: role.title,
      period: role.period,
      seniority: role.seniority,
    })),
    team: data.team,
    scope: data.scope?.trim(),
    responsibilities: data.responsibilities ?? [],
    technologies: data.technologies ?? [],
    highlights,
    narrative: content.trim(),
  };
});

// Sort most recent first, by the start of the top-level `period` field
// (format is "YYYY-MM - YYYY-MM" or "YYYY-MM - Present"/"present").
experiences.sort((a, b) => b.period.localeCompare(a.period));

// The per-role files above cover everything role-specific; the master
// resume is the only source for an overall summary and education, which
// don't belong to any single role.
const resumePath = join(careerEngineRoot, 'master-cv/master-resume-en.md');
const resumeText = readFileSync(resumePath, 'utf8');
const section = (heading) => {
  const match = resumeText.match(new RegExp(`## ${heading}\\n\\n([\\s\\S]*?)\\n\\n## `));
  return match?.[1].trim();
};
const profile = {
  summary: section('Summary'),
  education: (section('Education') ?? '')
    .split('\n')
    .filter((line) => line.startsWith('- '))
    .map((line) => line.slice(2).trim()),
};

const output = `// Generated by scripts/import-career-engine.mjs from career-engine's
// career/experiences/*.md — do not hand-edit. Re-run the script instead.
// Source: ${careerEngineRoot}

export interface ExperienceRole {
  title: string;
  period: string;
  seniority: string;
}

export interface Experience {
  company: string;
  location: string;
  period: string;
  roles: ExperienceRole[];
  team?: string;
  scope?: string;
  responsibilities: string[];
  technologies: string[];
  highlights: string[];
  narrative: string;
  /** Slug of a related archive \`project\` entry, when one genuinely exists. */
  relatedProjectSlug?: string;
}

export interface CareerProfile {
  summary?: string;
  education: string[];
}

export const experiences: Experience[] = ${JSON.stringify(experiences, null, 2)};

export const profile: CareerProfile = ${JSON.stringify(profile, null, 2)};
`;

const outPath = join(import.meta.dirname, '../src/data/experience.ts');
writeFileSync(outPath, output);
console.log(`Wrote ${experiences.length} experience(s) to ${outPath}`);
